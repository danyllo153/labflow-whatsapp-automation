/** Páginas do laboratório (07 §5): o que cada uma mostra e filtra. A API já filtra pelas views do Power BI. */

export type Formato = "texto" | "data" | "dataHora" | "situacao";

export interface Coluna {
  chave: string;
  rotulo: string;
  formato?: Formato;
  principal?: boolean; // no celular, vira o título do cartão
}

export interface Filtro {
  chave: string; // nome do parâmetro na API
  rotulo: string;
  tipo: "data" | "texto" | "numero" | "opcoes";
  opcoes?: string[];
  rotulos?: Record<string, string>; // valor → texto na tela (ex.: "true" → "Sim")
  dica?: string;
}

export interface DefinicaoDePagina {
  caminho: string; // /paginas/<caminho>
  titulo: string;
  descricao: string;
  api: string;
  colunas: Coluna[];
  filtros: Filtro[];
  impressao: "em pé" | "deitado"; // 07: em pé para listas estreitas, deitado para tabelas largas
  semColetor?: boolean; // 07: o Coletor não vê esta página
  resultado?: { tipo: "tendencia"; data: string; api?: string } | { tipo: "positivos"; teste: "TAB" | "Coliformes" }; // gráfico de resultado no lugar do Dashboard (26/10)
  grupo: "Geral" | "NFC" | "FCOJ" | "Testes"; // como a lista de páginas agrupa (pedidos de 23 e 24/10)
  oculta?: boolean; // não aparece na lista, mas o endereço continua abrindo (links antigos)
  linkDaLinha?: (linha: Record<string, unknown>) => string; // tocar na linha abre a página do item
  fixos?: Record<string, string>; // filtro sempre aplicado na API (ex.: uma página por teste, 24/10)
  dashboard?: { tipo: "colunas" | "tendencia"; coluna: string; aberto?: boolean }; // gráfico que o Dashboard mostra primeiro (25/10)
}

